#!/usr/bin/env python3
"""Extract the frozen v10 English declarations; never write into legacy/."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
SOURCE = "legacy/source/Playnite/Localization/LocSource.xaml"
CONSTANTS = "legacy/source/Playnite/Localization/LocalizationKeys.cs"
GENERATOR = "legacy/build/buildLocConstants.ps1"


def generate():
    entries = {}
    for node in ET.parse(ROOT / SOURCE).getroot():
        key = node.get("{http://schemas.microsoft.com/winfx/2006/xaml}Key")
        value = "".join(node.itertext())
        if not key or not value:
            continue
        if key in entries:
            raise ValueError(f"Duplicate key: {key}")
        entries[key] = value
    entries = dict(sorted(entries.items()))
    constants = dict(re.findall(r'public const string (\w+) = "([^"]+)";',
                               (ROOT / CONSTANTS).read_text(encoding="utf-8-sig")))
    expected = {key[3:] if key.startswith("LOC") else key: key for key in entries}
    if constants != expected:
        raise ValueError("Source declarations differ from frozen v10 constants")
    provenance = {
        "oracle": "Playnite 10.64 frozen legacy tree",
        "generator": "python3 scripts/loc/generate_english.py",
        "inputs": {path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
                   for path in (SOURCE, CONSTANTS, GENERATOR)},
        "keyCount": len(entries),
        "textContract": "XML-decoded character data, preserving source whitespace; not rendered XAML",
    }
    loc = "// Generated by scripts/loc/generate_english.py from frozen v10 declarations.\nnamespace Playnite;\n\npublic static class LOC\n{\n"
    loc += "".join(f'    public const string {name} = "{key}";\n'
                   for name, key in sorted(expected.items()))
    loc += "}\n"
    return {
        "src/Playnite.Core/Localization/English.json": json.dumps(entries, ensure_ascii=False, indent=2) + "\n",
        "src/Playnite.Core/Localization/LOC.cs": loc,
        "tests/golden/loc/english-v10.json": json.dumps({"provenance": provenance, "entries": entries}, ensure_ascii=False, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without modifying any files")
    args = parser.parse_args()
    for relative, content in generate().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                raise SystemExit(f"Stale localisation artifact: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    print("English localisation artifacts verified" if args.check else "English localisation artifacts generated")


if __name__ == "__main__":
    main()
